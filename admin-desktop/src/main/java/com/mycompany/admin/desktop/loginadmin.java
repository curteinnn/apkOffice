    private void bloginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bloginActionPerformed
        String username = tuser.getText().trim();
        String password = tpass.getText();

        if (username.isEmpty() || password.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Username dan password wajib diisi.",
                "Login", javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        blogin.setEnabled(false);
        blogin.setText("Memproses...");

        // HTTP dijalankan di background agar tampilan Swing tidak freeze.
        new javax.swing.SwingWorker<AuthResult, Void>() {
            @Override
            protected AuthResult doInBackground() throws Exception {
                ObjectMapper mapper = new ObjectMapper();
                String requestJson = mapper.createObjectNode()
                    .put("username", username)
                    .put("password", password)
                    .toString();

                HttpClient client = HttpClient.newBuilder()
                    .connectTimeout(Duration.ofSeconds(10))
                    .build();

                HttpRequest request = HttpRequest.newBuilder()
                    .uri(URI.create("http://localhost:8080/api/auth/login"))
                    .timeout(Duration.ofSeconds(15))
                    .header("Content-Type", "application/json")
                    .POST(HttpRequest.BodyPublishers.ofString(requestJson))
                    .build();

                HttpResponse<String> response = client.send(
                    request, HttpResponse.BodyHandlers.ofString()
                );

                JsonNode body = mapper.readTree(response.body());
                if (response.statusCode() < 200 || response.statusCode() >= 300) {
                    String message = body.hasNonNull("message")
                        ? body.get("message").asText()
                        : "Login gagal. Periksa username dan password.";
                    throw new IOException(message);
                }

                String token = body.path("token").asText("");
                String role = body.path("role").asText("");
                String nama = body.path("namaLengkap").asText(username);
                long id = body.path("id").asLong(-1);

                if (token.isBlank()) {
                    throw new IOException("Token tidak ditemukan dari server.");
                }
                if (!"ADMIN".equalsIgnoreCase(role)) {
                    throw new IOException("Akun ini bukan Admin. Role: " + role);
                }

                return new AuthResult(id, username, nama, role, token);
            }

            @Override
            protected void done() {
                blogin.setEnabled(true);
                blogin.setText("Login");
                try {
                    AuthResult result = get();
                    AuthSession.set(result);
                    javax.swing.JOptionPane.showMessageDialog(
                        loginadmin.this, "Login berhasil. Selamat datang, " + result.namaLengkap + "!"
                    );
                    Dashboard dashboard = new Dashboard();
                    dashboard.setVisible(true);
                    loginadmin.this.dispose();
                } catch (java.util.concurrent.ExecutionException ex) {
                    Throwable cause = ex.getCause();
                    String message = cause == null ? "Terjadi kesalahan saat login." : cause.getMessage();
                    javax.swing.JOptionPane.showMessageDialog(
                        loginadmin.this, message,
                        "Login Gagal", javax.swing.JOptionPane.ERROR_MESSAGE
                    );
                } catch (InterruptedException ex) {
                    Thread.currentThread().interrupt();
                    javax.swing.JOptionPane.showMessageDialog(
                        loginadmin.this, "Proses login terhenti.",
                        "Login Gagal", javax.swing.JOptionPane.ERROR_MESSAGE
                    );
                }
            }
        }.execute();
    }//GEN-LAST:event_bloginActionPerformed

